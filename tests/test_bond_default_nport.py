def test_zip_traversal_and_expansion_bounds(tmp_path: Path) -> None:
    path = tmp_path / "evil.zip"
    with zipfile.ZipFile(path, "w") as archive:
        archive.writestr("../evil.tsv", b"x")
    sha = nport.sha256_file(path)
    with pytest.raises(nport.ZipSafetyError):
        nport.parse_dera_package(path, expected_sha256=sha, package_label="e", output_dir=tmp_path / "o",
                                 work_dir=tmp_path / "w", retrieved_at=RETRIEVED)
    big = tmp_path / "big.zip"
    sha = b.build_zip(big, b.tables([filing(1).hold(1, CUSIP_A)]))
    with pytest.raises(nport.ZipSafetyError):
        nport.parse_dera_package(big, expected_sha256=sha, package_label="b", output_dir=tmp_path / "o2",
                                 work_dir=tmp_path / "w", retrieved_at=RETRIEVED,
                                 limits=nport.ZipLimits(max_member_bytes=64))
    bomb = tmp_path / "bomb.zip"
    with zipfile.ZipFile(bomb, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("SUBMISSION.tsv", b"A" * 5_000_000)
    with pytest.raises(nport.ZipSafetyError):
        nport.inspect_zip(zipfile.ZipFile(bomb), nport.ZipLimits(max_compression_ratio=100))


