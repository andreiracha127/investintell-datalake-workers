def test_proposal_carries_every_dependency() -> None:
    corr = corroboration()
    n_day = dt.date(2020, 12, 31)
    votes = [vote("S1", "0000000101", "N", day=n_day), vote("S2", "0000000102", "N", day=n_day),
             vote("S1", "0000000101", "Y"), vote("S3", "0000000103", "Y")]
    (proposal,) = consensus(votes, family_evidence=FAMILIES, corroborations=[corr]).proposals
    assert proposal.basis == "same_family_corroborated"
    assert set(corr.evidence_observation_ids) <= set(proposal.evidence_observation_ids)
    assert proposal.corroboration_adjudication_ids == (corr.adjudication_id,)
    assert proposal.corroboration_evidence_refs == corr.evidence_refs
    y_ids = {i for v in votes[2:] for i in v.y_observation_ids}
    n_ids = {i for v in votes[:2] for i in v.n_observation_ids}
    assert set(proposal.onset_upper_evidence_ids) == y_ids and set(proposal.onset_lower_evidence_ids) == n_ids
    assert (y_ids | n_ids) <= set(proposal.evidence_observation_ids)
    assert {r.registrant_cik for r in proposal.family_evidence} == {"0000000101", "0000000102", "0000000103"}
    assert proposal.evidence_known_at == RETRIEVED


