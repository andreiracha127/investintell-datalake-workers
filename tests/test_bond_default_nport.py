def run(tmp_path: Path, filings: list, *, label: str = "2021q1_nport.zip", vintage: str = "2021q1",
        retrieved: dt.datetime = RETRIEVED, **zip_kwargs) -> nport.DeraPackageResult:
    tag = uuid.uuid4().hex[:6]
    path = tmp_path / f"{tag}_{label}"
    sha = b.build_zip(path, b.tables(filings), vintage=vintage, **zip_kwargs)
    return nport.parse_dera_package(
        path, expected_sha256=sha, package_label=label, output_dir=tmp_path / f"out_{tag}",
        work_dir=tmp_path / "work", retrieved_at=retrieved, duckdb_threads=2, duckdb_memory_limit="512MB",
    )


def observations(result: nport.DeraPackageResult, **kwargs) -> list[c.CreditObservation]:
    return list(nport.iter_package_observations(result, **kwargs))


def filing(n: int, cik: str = "0000000101", series: str | None = "S000000001", **kwargs) -> object:
    return b.Filing(f"00000000{n:02d}-21-000001", cik=cik, series=series, **kwargs)


