def test_reconciled_equal_dera_content_can_be_backdated(tmp_path: Path) -> None:
    dera = xml_twin_dera(tmp_path)
    header = xml_header(filing_date="20260812")
    xml = nport.parse_public_accession(xml_doc(), header=header, retrieved_at=RETRIEVED, official_url="u")
    rec = nport.reconcile_dera_with_public(dera, xml)
    assert rec.dera_package_id == str(dera.source_package.package_id) and rec.dera_zip_sha256 == dera.zip_sha256
    assert rec.xml_sha256 == xml.source_package.content_sha256 and rec.header_sha256 == header.header_sha256
    stored = nport.DeraReconciliation.from_record(json.loads(json.dumps(rec.to_record())))
    assert stored == rec
    notes = __import__("collections").Counter()
    (obs,) = [o for o in observations(dera, acceptance_headers={header.accession_number: header},
                                      reconciliations=[stored], time_notes=notes) if o.cusip9 == CUSIP_A]
    assert obs.public_time_basis == "edgar_acceptance_datetime"
    assert obs.public_available_at == dt.datetime(2026, 8, 12, 14, 15, tzinfo=UTC)
    assert notes == {"reconciled_with_public_xml": 1}
    tampered = dataclasses.replace(stored, dera_semantic_digest="0" * 64)
    with pytest.raises(nport.ReconciliationError):
        list(nport.iter_package_observations(dera, acceptance_headers={header.accession_number: header},
                                             reconciliations=[tampered]))
    other_header = dataclasses.replace(header, header_sha256="f" * 64)
    (unbound,) = [o for o in observations(dera, acceptance_headers={header.accession_number: other_header},
                                          reconciliations=[stored]) if o.cusip9 == CUSIP_A]
    assert unbound.public_time_basis == "first_verified_retrieval"  # reconciliation bound to another header


def test_projection_and_observations_are_deterministic_in_fresh_processes(tmp_path: Path) -> None:
    path = tmp_path / "det.zip"
    sha = b.build_zip(path, b.tables([filing(1).hold(1, CUSIP_A, is_default="Y").hold(2, "N/A",
                                      isins=[b.make_isin(CUSIP_B)]), filing(2, cik="0000000102").hold(3, CUSIP_A)]))
    script = (
        "import sys, json, datetime as dt\n"
        f"sys.path.insert(0, {str(ROOT)!r})\n"
        "from pathlib import Path\n"
        "from src.bonds.default_events import nport, contracts as c\n"
        "out = Path(sys.argv[1])\n"
        f"r = nport.parse_dera_package(Path({str(path)!r}), expected_sha256={sha!r}, package_label='d.zip',"
        " output_dir=out, work_dir=out / 'w', retrieved_at=dt.datetime(2026,9,25,tzinfo=dt.timezone.utc),"
        " duckdb_threads=2)\n"
        "print(c.frame_digest(o.row_sha256() for o in nport.iter_package_observations(r)))\n"
    )
    digests = []
    for i in range(2):
        done = subprocess.run([sys.executable, "-c", script, str(tmp_path / f"run{i}")], capture_output=True,
                              text=True, timeout=240, check=False)
        assert done.returncode == 0, done.stderr[-2000:]
        digests.append(done.stdout.strip())
    assert digests[0] == digests[1] and digests[0].startswith("sha256:")


