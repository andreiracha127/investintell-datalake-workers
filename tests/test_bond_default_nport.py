def xml_doc(*, sub_type: str = "NPORT-P", debt: str | None = None, cik: str = "0000000101",
            namespace: str = "http://www.sec.gov/edgar/nport", prefix: str = "") -> bytes:
    debt = debt if debt is not None else (
        "<debtSec><maturityDt>2030-01-15</maturityDt><couponKind>Fixed</couponKind>"
        "<annualizedRt>5.0</annualizedRt><isDefault>Y</isDefault><areIntrstPmntsInArrs></areIntrstPmntsInArrs>"
        "</debtSec>"
    )
    return (
        f'{prefix}<?xml version="1.0" encoding="UTF-8"?>'
        f'<edgarSubmission xmlns="{namespace}" xmlns:com="http://www.sec.gov/edgar/common" '
        'xmlns:ncom="http://www.sec.gov/edgar/nportcommon">'
        f"<headerData><submissionType>{sub_type}</submissionType><filerInfo><filer><issuerCredentials>"
        f"<cik>{cik}</cik></issuerCredentials></filer></filerInfo></headerData>"
        f"<formData><genInfo><regCik>{cik}</regCik><seriesId>S000000001</seriesId>"
        "<repPdDate>2026-06-30</repPdDate></genInfo><invstOrSecs>"
        f"<invstOrSec><name>Synthetic</name><lei>N/A</lei><title>NOTE</title><cusip>{CUSIP_A}</cusip>"
        "<identifiers><isin value=\"US0378331005\"/></identifiers><balance>1000</balance><units>PA</units>"
        "<curCd>USD</curCd><valUSD>990</valUSD><assetCat>DBT</assetCat><issuerCat>CORP</issuerCat>"
        f"{debt}</invstOrSec>"
        "<invstOrSec><name>Muni</name><cusip>000000000</cusip><assetCat>DBT</assetCat>"
        '<issuerConditional issuerCat="OTHER" desc="x"/>'
        "<debtSec><isDefault>Y</isDefault></debtSec></invstOrSec>"
        "</invstOrSecs></formData></edgarSubmission>"
    ).encode()


def xml_header(sub_type: str = "NPORT-P", cik: str = "0000000101", filing_date: str | None = None
               ) -> sa.AcceptanceHeader:
    accession = "0000000101-26-000009"
    filed = "" if filing_date is None else f"<FILING-DATE>{filing_date}\n"
    doc = (f"<SEC-HEADER>\n<ACCEPTANCE-DATETIME>20260812101500\n<ACCESSION-NUMBER>{accession}\n<TYPE>{sub_type}\n"
           f"{filed}<CIK>{cik}\n</SEC-HEADER>").encode()
    return sa.parse_acceptance_header(doc, accession_number=accession, url="u", document_sha256="0" * 64,
                                      retrieved_at=RETRIEVED)


