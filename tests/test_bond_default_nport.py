def test_member_hash_reverification(tmp_path: Path) -> None:
    result = run(tmp_path, [filing(1).hold(1, CUSIP_A)])
    zip_path = next(tmp_path.glob("*_2021q1_nport.zip"))
    members = dict(result.source_package.member_sha256s)
    nport.verify_member_hashes(zip_path, expected_sha256=result.zip_sha256, expected_members=members)
    tampered = {**members, "DEBT_SECURITY.tsv": "0" * 64}
    with pytest.raises(nport.PackageIntegrityError, match="member_sha256_mismatch:DEBT_SECURITY.tsv"):
        nport.verify_member_hashes(zip_path, expected_sha256=result.zip_sha256, expected_members=tampered)
    with pytest.raises(nport.PackageIntegrityError, match="member_missing"):
        nport.verify_member_hashes(zip_path, expected_sha256=result.zip_sha256,
                                   expected_members={**members, "X.tsv": "0" * 64})
    with pytest.raises(nport.PackageIntegrityError, match="package_sha256_mismatch"):
        nport.verify_member_hashes(zip_path, expected_sha256="1" * 64, expected_members=members)


