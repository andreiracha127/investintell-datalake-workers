@pytest.mark.parametrize(
    "case,failed",
    [
        # A mapping that disappeared: a new missing, never an aged listing.
        ("new_missing", {"additions_stale_only", "counts_conserved"}),
        # The retained key's timestamp moved BACKWARDS (source reconstruction).
        ("reconstructed_older_row", {"additions_aging_window"}),
        # A new related (same ticker) historical identity appeared.
        ("new_related_identity", {"additions_aging_window"}),
        # A retained missing fund now has an OLD row: relabel missing -> stale.
        ("relabel_missing_to_stale", {"intersection_reasons_unchanged"}),
        # Fresh at tau_live, but the listing predates tau_v2: no relisting.
        ("fresh_without_new_listing", {"removals_fresh_relisted"}),
        # A non-SEC decision moved (activity unknown -> active).
        (
            "non_sec_decision_moved",
            {"universe_and_pre_sec_unchanged", "only_sec_movements"},
        ),
        # A retained missing fund leaves E through a lost registry claim, not a
        # fresh relisting: an invalid removal and a changed pre-SEC set.
        (
            "removal_by_lost_registry",
            {"removals_fresh_relisted", "universe_and_pre_sec_unchanged"},
        ),
    ],
)
def test_reconciliation_stops_on_unexplained_movement(
    calendar, v2_raw, pinned_config, case, failed
):
    tau_live, entities = TAU_LIVE, None
    if case == "new_missing":
        sec = _live_sec(tau_live, drop={8})
    elif case == "reconstructed_older_row":
        sec = _live_sec(tau_live, rows={8: sec_row(8, synced=V2_FRESH - 2 * DAY)})
    elif case == "new_related_identity":
        sec = _live_sec(
            tau_live,
            not_refreshed={8},
            extra=[sec_row(808, ticker="T8", series="S000000008", synced=V2_FRESH)],
        )
    elif case == "relabel_missing_to_stale":
        sec = _live_sec(tau_live, extra=[sec_row(6, synced=V2_STALE)])
    elif case == "fresh_without_new_listing":
        tau_live = TAU_V2 + 3 * DAY
        sec = _live_sec(
            tau_live, rows={3: sec_row(3, synced=TAU_V2 - dt.timedelta(hours=1))}
        )
    elif case == "removal_by_lost_registry":
        entities = _entities()
        entities[5] = only(entity(6), registry=False)
        sec = _live_sec(tau_live, extra=[sec_row(6, synced=tau_live - DAY)])
    else:  # non_sec_decision_moved
        entities = _entities()
        entities[21] = entity(22)
        sec = _live_sec(tau_live, extra=[sec_row(22, synced=tau_live - DAY)])
    live, report = _live_bundle(
        calendar, pinned_config, tau_live=tau_live, sec=sec, entities=entities
    )
    assert verifier.verdict_of(report, strict=True), report["gates"]
    passed, document = _reconcile(v2_raw, live, pinned_config)
    assert not passed and document["status"] == "stop"
    assert failed <= set(_failed(document)), _failed(document)
    base._assert_shareable(document)


