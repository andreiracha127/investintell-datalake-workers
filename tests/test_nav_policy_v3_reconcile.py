    base._assert_text_shareable(printed)
    expected = {
        "wrong_sha": "live_policy_sha256_mismatch",
        "blocked_live": "operator:audit_dossier_invalid",
    }
    if case in expected:
        assert blocked["code"] == expected[case]
    assert not (tmp_path / "outside.json").exists()
    if case == "symlink_output":
        assert (root / "target.json").read_bytes() == b"{}"


