# ── CLI (POSIX custody) ─────────────────────────────────────────────────────
def _cli_args(
    tmp_path, v2_raw, live, config_raw, *, monkeypatch, output=None, custody=None
):
    root = tmp_path / "custody"
    root.mkdir(mode=0o700)
    v2_bundle, v2_config_raw = _v2_bundle(v2_raw)
    args = []
    for prefix, bundle in (("v2", v2_bundle), ("live", live)):
        for key, raw in bundle.items():
            path = root / f"{prefix}-{key}.json"
            path.write_bytes(raw)
            flag = f"{prefix}-{key.replace('_', '-')}"
            args += [
                f"--{flag}-file",
                str(path),
                f"--{flag}-sha256",
                hashlib.sha256(raw).hexdigest(),
            ]
    (root / "v2-config.json").write_bytes(v2_config_raw)
    (root / "config.json").write_bytes(config_raw)
    expected = tmp_path / "expected.json"
    expected.write_bytes(json.dumps(EXPECTED).encode())
    monkeypatch.setattr(reconcile, "EXPECTED_PATH", expected)
    args += [
        "--v2-audit-config",
        str(root / "v2-config.json"),
        "--audit-config",
        str(root / "config.json"),
        "--custody-root",
        str(custody or root),
        "--output",
        str(output or root / "reconcile.json"),
    ]
    return root, args


