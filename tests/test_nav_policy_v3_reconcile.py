def test_cli_blocks_with_static_code_only(
    calendar, v2_raw, pinned_config, tmp_path, capsys, monkeypatch, case
):
    sec = (
        _live_sec(TAU_LIVE, not_refreshed={8, 9, 10, 11})
        if case == "blocked_live"
        else None
    )
    live, _ = _live_bundle(calendar, pinned_config, sec=sec)
