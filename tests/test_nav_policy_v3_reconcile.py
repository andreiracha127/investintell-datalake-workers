# ── live Round7 bundle builder (upsert-only SEC evolution) ──────────────────
def _live_sec(
    tau_live, *, not_refreshed=(), refresh_at=None, rows=None, extra=(), drop=()
):
    """Every v2-fresh row is upserted again just before ``tau_live`` unless in
    ``not_refreshed`` (the v2 stale rows are never refreshed); ``rows``
    replaces single rows, ``extra`` adds rows, ``drop`` removes a row."""
    at = refresh_at or tau_live - dt.timedelta(hours=1)
    evolved = {}
    for n, row in _v2_sec().items():
        if n in drop:
            continue
        refreshed = n not in base.STALE_IDS and n not in not_refreshed
        evolved[n] = dict(row, synced_at=at if refreshed else row["synced_at"])
    evolved.update(rows or {})
    return [*evolved.values(), *extra]


def _previous(calendar) -> bytes:
    document = {
        "policy_id": POLICY_ID,
        "policy_version": "2026-09-23.1",
        "generator_version": "fund-nav-policy-generator-v1",
        "instrument_evidence": [
            {"instrument_id": str(uuid.UUID(int=1)), "fund_status": "ACTIVE"},
            {"instrument_id": str(uuid.UUID(int=23)), "fund_status": "INACTIVE"},
        ],
    }
    for field in verifier.CALENDAR_CONTINUITY_FIELDS:
        document[field] = calendar[field]
    return json.dumps(document, sort_keys=True).encode()


def _live_bundle(
    calendar, config_raw, *, tau_live=TAU_LIVE, sec=None, entities=None, captured=None
):
    """Generate at ``tau_live``, capture the same four sources, audit strictly
    and link the canary exactly as ``verify_fund_nav_identity_v2.main`` does."""
    entities = entities or _entities()
    sec = _live_sec(tau_live) if sec is None else sec
    instruments, funds, identity, sec_rows = catalog(*entities, sec=sec)
    policy = generator.build_policy(
        calendar,
        instruments,
        funds,
        identity,
        sec_rows,
        tau_live,
        POLICY_ID,
        POLICY_VERSION,
    )
    snapshot = generator.build_source_snapshot(
        policy, instruments, funds, identity, sec_rows
    )
    policy_raw = generator.canonical_json(policy)
    config = json.loads(config_raw)
    live = {
        "captured_at": captured or tau_live + dt.timedelta(minutes=5),
        "sources": {"instruments": instruments, "funds": funds, "identity": identity},
        "cohort": {
            "state": "captured",
            "rows": [
                {"instrument_id": uuid.UUID(int=n), "strategy_label": base.LABEL}
                for n in range(1, 23)
            ],
        },
        "sec": {
            "state": "captured",
            "rows": [dict(row) for row in sec_rows],
            "lineage": {
                "row_count": len(sec_rows),
                "min_synced_at": min(row["synced_at"] for row in sec_rows),
                "max_synced_at": max(row["synced_at"] for row in sec_rows),
            },
        },
    }
    capture_raw = verifier.capture_bytes(live, config)
    previous = _previous(calendar)
    report = verifier.audit(
        policy_raw,
        snapshot_raw=generator.canonical_json(snapshot),
        capture_raw=capture_raw,
        previous_raw=previous,
        config_raw=config_raw,
    )
    passed = verifier.verdict_of(report, strict=True)
    report["result"] = "pass" if passed else "fail"
    report["strict"] = True
    report["canary_requested"] = True
    audit_raw = verifier.report_bytes(report)
    canary_raw = operator._document_bytes({})
    if passed:
        canary = verifier.build_canary(
            report,
            policy_raw,
            config,
            audit_report_sha256=hashlib.sha256(audit_raw).hexdigest(),
        )
        canary_raw = (
            json.dumps(canary, sort_keys=True, separators=(",", ":")) + "\n"
        ).encode("ascii")
    return {
        "policy": policy_raw,
        "source_snapshot": generator.canonical_json(snapshot),
        "capture": capture_raw,
        "audit": audit_raw,
        "canary": canary_raw,
        "previous_policy": previous,
    }, report


def _v2_bundle(v2_raw):
    policy_raw, snapshot_raw, capture_raw, audit_raw, v2_config_raw = v2_raw
    bundle = {
        "policy": policy_raw,
        "source_snapshot": snapshot_raw,
        "capture": capture_raw,
        "audit": audit_raw,
    }
    return bundle, v2_config_raw


def _reconcile(v2_raw, live_bundle, config_raw, expected=EXPECTED):
    v2_bundle, v2_config_raw = _v2_bundle(v2_raw)
    return reconcile.reconcile(
        v2_bundle=v2_bundle,
        live_bundle=live_bundle,
        v2_config_raw=v2_config_raw,
        config_raw=config_raw,
        expected_raw=json.dumps(expected).encode(),
    )


def _failed(document):
    return [name for name, ok in document["checks"].items() if not ok]


